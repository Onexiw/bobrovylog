<p>
	Результаты проведенной аттестации рабочих мест по условиям труда (специальной оценки условий труда) позволили определить состояние условий труда на каждом рабочем месте, провести мероприятия по улучшению и оздоровления условий труда, расширить перечень выдаваемой спецодежды и средств защиты, конкретизировать льготы за работу во вредных условиях труда, прохождение периодических медицинских осмотров.</p>
<p>
	<strong>С 28.03. по 28.04.2018 г. в ООО «Ренонс» проводился месячник по охране труда, приуроченный к Всемирному дню охраны труда (28 апреля) под девизом «Основа эффективного производства – соблюдение требований по ОТ!»</strong></p>
<p>
	Этот день был объявлен по инициативе Международной организации труда в 2003 г. в память о рабочих, погибших, получивших увечье на рабочем месте или страдающих от профессиональных заболеваний. Здоровье работника, его жизнь признаются в современном обществе приоритетными по отношению к результатам производственной деятельности, в связи с чем необходимо повышать безопасность труда, снижать смертность и травматизм на рабочем месте.</p>
<p>
	В соответствии с «Программой проведения месячника по ОТ» был проведен смотр-конкурс среди подразделений по культуре охраны труда; конкурсы среди руководителей подразделений и работников Общества на знание государственных нормативных требований, а также локальных нормативных актов в области охраны труда.</p>
<p>
	Лучшим среди подразделений на смотре-конкурсе был признан Отдел главного энергетика. Среди руководителей лучшие знания продемонстрировал заместитель Отдела эксплуатации канатных дорог и аттракционов ООО «Ренонс». Лучший результат среди работников рабочих профессий выявлялся отдельно по каждому подразделению, победители были поощрены.</p>
