<p>
	<strong>Специальная оценка условий труда</strong></p>
<p >
	В соответствии с требованиями трудового законодательства, с целью осуществления контроля за состоянием условий труда на рабочих местах и подготовки мероприятий по улучшению и оздоровлению условий труда на рабочих местах, в 2013 г. проводилась аттестация рабочих мест по условиям труда.</p>
<p >
	По результатам аттестации рабочих мест в ООО «Ренонс» был разработан «План мероприятий по улучшению и оздоровлению условий труда», в соответствии с которым в 2013 – 2014 гг. были реализованы следующие мероприятия:</p>
<p >
	- в «Правилах внутреннего трудового распорядка» установлены регламентированные перерывы с учетом воздействия вредных производственных факторов;</p>
<p >
	- организована выдача работникам смывающих и обезвреживающих средств в соответствии с типовыми нормами и ведение личных карточек учета выдачи смывающих и обезвреживающих средств;</p>
<p >
	- осуществляется приобретение и выдача сертифицированных средств индивидуальной защиты;</p>
<p >
	- организовано обучение персонала, обслуживание водоподготовку воды в бассейнах;</p>
<p >
	- организовано приобретение и замена осветительных приборов на рабочих местах для приведения уровня освещенности и пульсации к нормативным показателям;</p>
<p >
	- помещения водоподготовки воды в бассейнах оборудованы стационарными газоанализаторами.</p>
<p >
	В связи с досрочным осуществлением мероприятий по улучшению условий труда работников, на тех рабочих местах, на которых вредные производственные факторы были устранены полностью (административно-управленческий персонал – 34 рабочих места), в ООО «Ренонс» в 2014 г. была проведена специальная оценка условий труда. Специальная оценка условий труда подтвердила, что условий труда на данных рабочих местах приведены к допустимым (2 класс).</p>
