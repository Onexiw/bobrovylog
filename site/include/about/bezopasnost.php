<h4>
	<strong>Охрана труда в ООО «Ренонс»</strong></h4>
<p>
	ООО «Ренонс» входит в Группу компаний ПАО «ГМК «Норильский никель» и в своей работе руководствуется Политикой ПАО «ГМК «Норильский никель» в области охраны труда и промышленной безопасности, которая провозглашает принцип приоритетности жизни и здоровья работников по отношению к результатам производственной деятельности и декларирует заинтересованность Компании в создании здоровых и безопасных условий труда для всех работников и формировании у них устойчивого мотивационного механизма безопасного поведения на производстве.</p>
<p>
	В ООО «Ренонс» сформирована Система управления промышленной безопасностью и охраной труда, которая определяет порядок организации и проведения работы по промышленной безопасности и охране труда в соответствии с действующим законодательством, нормативными актами в области ПБиОТ ПАО «ГМК «Норильский никель», достижениями науки, сложившейся практикой в этом направлении.</p>
<p>
	В рамках существующей Системы управления промышленной безопасностью и охраной труда в ООО «Ренонс» осуществляются организационные, технические, санитарно-гигиенические и профилактические мероприятий, направленных на обеспечение безопасности, сохранение здоровья и жизни человека в процессе труда, сокращение уровня производственного травматизма, общей и профессиональной заболеваемости; на предупреждение, предотвращение и ликвидации аварий, инцидентов и несчастных случаев на опасных производственных объектах.</p>
<p>
	В ООО «Ренонс»:</p>
<p>
	- на всех уровнях управления производством установлены определенные функций и обязанностей по ПБиОТ для руководителей, специалистов и рабочих;</p>
<p>
	- осуществляется общее руководство и контроль за соблюдением требований ПБиОТ в Обществе, контроль за соблюдением законодательных и иных нормативных правовых актов, требований, правил и инструкций по ОТ, производственных инструкций, контроль за выполнением служебных обязанностей подчиненными;</p>
<p>
	- ежегодно планируются мероприятий по обеспечению здоровых и безопасных условий труда, безопасности технологических процессов и оборудования; организуется их исполнения, обеспечивается выделения финансовых средств на их реализацию;</p>
<p>
	- организуется подготовка персонала (обучение работников методам и приемам безопасного производства работ, проверка знаний, аттестация, стажировка, инструктаж);</p>
<p>
	- работники обеспечиваются средствами защиты от воздействия опасных и вредных производственных факторов;</p>
<p>
	- организуется проведение предварительных (при приеме на работу) и периодических медицинских осмотров работников, а также предрейсовых и послерейсовых осмотров водителей автотранспортных средств;</p>
<p>
	- санитарно-гигиенических условия труда на рабочих местах поддерживаются в соответствие с нормами;</p>
<p>
	- для работников создаются благоприятные социальные условия, установлены оптимальные режимы труда и отдыха;</p>
<p>
	- осуществляются мероприятия по снижению риска аварий, инцидентов и несчастных случаев на опасных производственных объектах;</p>
<p>
	- установлен порядок обеспечения пожарной безопасности на объектах.</p>
