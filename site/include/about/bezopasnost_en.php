<p>
	 Funpark “Bobrovy Log” is a modern Complex. It was built for those locals of the city and the Krasnoyarsk territory who are fond of sports and active way of life. The Complex was constructed living up to the latest technologies. Besides excellent service all the visitors need to be sure of their own security especially when they are enjoying their time with family and kids. That is why we pay special attention to security in the Funpark keep on working at each direction. Everything is important: technical condition of each object, the quality of slope preparation, means of protection, qualified instructions, experienced rescuers in case of emergency, an ability to get to a first-aid post and a security post.
</p>
<p>
	 While in service all the objects in the Funpark get regular technical inspection to check both engineering status and security level. Every week the facility maintenance service carries out scheduled works and every year competent public authorities give their technical certification.
</p>
<p>
	 Visitors’ safety on the pistes and attractions is ensured by active protective equipment such as protective nets along the pistes, drop off and pick up zones, there are also safety mats in dangerous areas. Among passive protective equipment there are behavior rules, warning notes and signs on each attraction. The entire territory of the Funpark is equipped with the alerting sound system. The background sound system informs visitors about behavior rules, services and events in the Funpark, in case you need it you can also make your own announcement.
</p>
<p>
	 In winter a special rescuer service patrols the pistes. During the summer season they watch visitors not break behavior rules in the swimming pool zone, they also give first aid for those who need. All the rescue workers are greatly experienced and certified by the Ministry of Emergency Situations.
</p>
<p>
	 Thanks to excellent job of highly qualified specialists and seamless interaction of all the Funpark services we can be sure of out visitors’ security within the whole year.
</p>
<p>
	 There are two four sits chairlifts by the Austrian company Doppelmayer – K1 and K2. There is also a two sits T-bar lift – Б1.
</p>
