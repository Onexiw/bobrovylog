<p>
 <b>Охрана труда в ООО «Ренонс»</b>
</p>
<p>
</p>
<p>
	 ООО «Ренонс» входит в Группу компаний ПАО «ГМК «Норильский никель» и в своей работе руководствуется Политикой ПАО «ГМК «Норильский никель» в области охраны труда и промышленной безопасности, которая провозглашает принцип приоритетности жизни и здоровья работников по отношению к результатам производственной деятельности и декларирует заинтересованность Компании в создании здоровых и безопасных условий труда для всех работников и формировании у них устойчивого мотивационного механизма безопасного поведения на производстве. <br>
	 В ООО «Ренонс» сформирована Система управления промышленной безопасностью и охраной труда, которая определяет порядок организации и проведения работы по промышленной безопасности и охране труда в соответствии с действующим законодательством, нормативными актами в области ПБиОТ ПАО «ГМК «Норильский никель», достижениями науки, сложившейся практикой в этом направлении. <br>
	 В рамках существующей Системы управления промышленной безопасностью и охраной труда в ООО «Ренонс» осуществляются организационные, технические, санитарно-гигиенические и профилактические мероприятий, направленных на обеспечение безопасности, сохранение здоровья и жизни человека в процессе труда, сокращение уровня производственного травматизма, общей и профессиональной заболеваемости; на предупреждение, предотвращение и ликвидации аварий, инцидентов и несчастных случаев на опасных производственных объектах. <br>
	 В ООО «Ренонс»: <br>
	 - на всех уровнях управления производством установлены определенные функций и обязанностей по ПБиОТ для руководителей, специалистов и рабочих; <br>
	 - осуществляется общее руководство и контроль за соблюдением требований ПБиОТ в Обществе, контроль за соблюдением законодательных и иных нормативных правовых актов, требований, правил и инструкций по ОТ, производственных инструкций, контроль за выполнением служебных обязанностей подчиненными; <br>
	 - ежегодно планируются мероприятий по обеспечению здоровых и безопасных условий труда, безопасности технологических процессов и оборудования; организуется их исполнения, обеспечивается выделения финансовых средств на их реализацию; <br>
	 - организуется подготовка персонала (обучение работников методам и приемам безопасного производства работ, проверка знаний, аттестация, стажировка, инструктаж); <br>
	 - работники обеспечиваются сертифицированными средствами защиты от воздействия опасных и вредных производственных факторов, смывающими и обезвреживающими средствами; <br>
	 - организуется проведение предварительных (при приеме на работу) и периодических медицинских осмотров работников, а также предрейсовых и послерейсовых осмотров водителей автотранспортных средств; <br>
	 - санитарно-гигиенических условия труда на рабочих местах поддерживаются в соответствие с нормами; <br>
	 - для работников создаются благоприятные социальные условия, установлены оптимальные режимы труда и отдыха; <br>
	 - осуществляются мероприятия по снижению риска аварий, инцидентов и несчастных случаев на опасных производственных объектах; <br>
	 - установлен порядок обеспечения пожарной безопасности на объектах.
</p>
