<p>
	 Фанпарк «Бобровый лог» - современный комплекс, построенный для жителей города и края, предпочитающих спорт и активный образ жизни, исключительно по последнему слову техники с применением высоких технологий. Для любого посетителя кроме отличного сервиса важна уверенность в собственной безопасности, тем более, если речь идет об отдыхе всей семьей с детьми. Поэтому вопросам безопасности в Фанпарке уделяется особое внимание, и по всем направлениям ведется непрерывная работа. Важно все: и техническое состояние каждого объекта, и качество подготовки склонов, и средства защиты, и грамотный инструктаж, и наличие опытных спасателей, и даже, в случае необходимости, возможность обратиться в медпункт или охрану комплекса.
</p>
<p>
	 В течение эксплуатации все объекты Фанпарка проходят плановые обследования на предмет технического состояния и уровня безопасности. Еженедельно служба эксплуатации объектов проводит регламентные работы, ежегодно компетентные государственные органы - технические освидетельствования.
</p>
<p>
	 Безопасное пребывание посетителей на склонах и аттракционах обеспечивается при помощи активных (специальные защитные сетки вдоль трасс, на зонах посадки и высадки, защитные маты на опасных участках) и пассивных средств защиты (правила поведения на каждом конкретном объекте, предупредительные знаки и надписи). На всей территории комплекса установлена система звукового оповещения. С помощью фонового звучания посетители узнают информацию о правилах поведения, услугах и мероприятиях Фанпарка, а также могут сделать свое объявление.
</p>
<p>
	 Специальная служба спасателей зимой патрулирует трассы, летом дежурит у бассейна с целью предотвращения нарушений правил поведения посетителями, оказывает первую доврачебную помощь пострадавшим. Все спасатели обладают большим опытом, и имеют сертификацию специализированных курсов МЧС.
</p>
<p>
	 Благодаря профессиональной работе высококвалифицированных специалистов и слаженному взаимодействию всех служб Фанпарка мы можем быть уверены в безопасном пребывании посетителей на комплексе в любое время года.
</p>
