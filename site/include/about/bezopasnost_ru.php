 Этот день был объявлен по инициативе Международной организации труда в 2003 г. в память о рабочих, погибших, получивших увечье на рабочем месте или страдающих от профессиональных заболеваний. Здоровье работника, его жизнь признаются в современном обществе приоритетными по отношению к результатам производственной деятельности, в связи с чем необходимо повышать безопасность труда, снижать смертность и травматизм на рабочем месте.
